const { chromium } = require('playwright');
const { Pool } = require('pg');
const db = new Pool({ host: '127.0.0.1', user: 'postgres', password: 'pw', database: 'biztest' });
const results = []; const check = (n, ok, x = '') => { results.push(ok); console.log(ok ? 'PASS' : 'FAIL', n, x); };
(async () => {
  await db.query("TRUNCATE bi_contacts, companies, contact_notes, contact_activities CASCADE");
  await db.query("insert into bi_contacts (first_name,last_name,email,status,company) select 'Person'||lpad(g::text,3,'0'), 'Test', 'p'||g||'@x.com', case when g%4=0 then 'customer' else 'lead' end, case when g=77 then 'Zebra Corp' else 'Acme' end from generate_series(1,120) g");
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } });
  await ctx.addInitScript(() => localStorage.setItem('walkthrough_completed', 'true'));
  const page = await ctx.newPage(); const errs = []; page.on('pageerror', e => errs.push(e.message));
  const rowsN = () => page.locator('tbody tr').count();
  const wait = async n => { try { await page.waitForFunction(k => document.querySelectorAll('tbody tr').length === k, n, { timeout: 8000 }); return true; } catch { return false; } };
  await page.goto('http://localhost:5111/app/contacts-hub'); 
  check('first page shows 50 of 120', await wait(50) && /1–50 of 120/.test(await page.locator('[data-testid=pager]').innerText()));
  await page.click('[aria-label="Next page"]'); await page.waitForTimeout(800);
  check('page 2 range', /51–100 of 120/.test(await page.locator('[data-testid=pager]').innerText()));
  await page.click('[aria-label="Next page"]'); await wait(20);
  check('last page has 20 rows, Next disabled', (await rowsN()) === 20 && await page.locator('[aria-label="Next page"]').isDisabled());
  await page.fill('input[placeholder="Search contacts…"]', 'zebra');
  check('server search by company finds 1 and resets to page 1', await wait(1) && /1–1 of 1/.test(await page.locator('[data-testid=pager]').innerText()));
  await page.fill('input[placeholder="Search contacts…"]', '50%_');
  await page.waitForTimeout(900);
  check('special characters do not error', errs.length === 0);
  await page.fill('input[placeholder="Search contacts…"]', '');
  await page.selectOption('select >> nth=0', 'customer');
  check('status filter is server-side (30 customers)', await wait(30) && /1–30 of 30/.test(await page.locator('[data-testid=pager]').innerText()));
  await page.selectOption('select >> nth=0', 'all'); await wait(50);
  await page.click('th:has-text("Name")'); await page.waitForTimeout(1200);
  check('sort by name asc across whole set', (await page.locator('tbody tr td:nth-child(2)').first().innerText()) === 'Person001 Test');
  await page.click('th:has-text("Name")'); await page.waitForTimeout(1200);
  check('sort desc puts Person120 first', (await page.locator('tbody tr td:nth-child(2)').first().innerText()) === 'Person120 Test');
  const dl = page.waitForEvent('download');
  await page.click('button:has-text("Export")');
  const path = await (await dl).path(); const lines = require('fs').readFileSync(path, 'utf8').trim().split('\n').length;
  check('export covers all 120 rows (not just the page)', lines === 121, String(lines));
  check('no page errors', errs.length === 0, errs.slice(0, 2).join(';'));
  console.log(`\n${results.filter(Boolean).length}/${results.length} passed`);
  await b.close(); await db.end(); process.exit(results.every(Boolean) ? 0 : 1);
})().catch(e => { console.error('crashed', e.message.split('\n')[0]); process.exit(2); });
